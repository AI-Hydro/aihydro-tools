# Profile
# ---------------------------------------------------------------------------

def profile_block(max_bytes: int = PROFILE_MAX_BYTES) -> str:
    """Stored profile fields (neutralised, number-gated) as markdown, <= ``max_bytes`` UTF-8 bytes. Empty when no profile."""
    try:
        from ai_hydro.session.persona import ResearcherProfile

        p = ResearcherProfile.load()
    except Exception as exc:                      # an unreadable profile must not break the study digest
        log.warning("profile not read: %s", exc)
        return ""
    if p.is_blank():
        return ""
    fields = [
        ("Name", p.name), ("Role", p.role), ("Institution", p.institution), ("Domain", p.domain),
        ("Current focus", p.research_focus),
        ("Expertise", ", ".join(p.expertise) if p.expertise else ""),
        ("Communication style", p.communication_style),
    ]
    lines = ["## Researcher profile"]
    for label, value in fields:
        value = neutralise(value)
        if not value:
            continue
        line = f"**{label}**: {value}"
        if bare_numbers(line):
            continue                               # a number in a profile field is not a cited result
        if len("\n".join(lines + [line]).encode("utf-8")) > max_bytes:
            break
        lines.append(line)
    return "\n".join(lines) if len(lines) > 1 else ""


