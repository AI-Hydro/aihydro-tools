"""Active-study context (T-R1): the section a host injects into the prompt, and the ``research.md`` stub.

``build_context(project_id, chat_id)`` assembles, for ONE chat, the digest of its active study plus the
researcher profile. It backs the resource ``aihydro://project/{prj}/context?chat=``. Rules:

* **Only the chat's active study.** The study is the one bound to the chat (``ChatBindingStore``) and it
  must belong to the project. There is no "default study" or "most recent study" fallback: with no
  binding the section says so and shows no study. Other studies, other projects and other chats never
  appear.
* **No side effects.** Nothing is bound, created, saved or migrated; a missing project, chat or study
  is reported in the output, not repaired.
* **Pointers, not remembered numbers (B6).** A measured value is read from its run-log row at call time
  and rendered in audit grammar: ``baseflow_index = 0.44 [run:<id>#key_outputs.baseflow_index]``. A row
  whose seal fails renders as ``stale pointer`` with no value. Every other line is names, labels,
  identifiers and dates. A final gate withholds any line that still carries a numeric literal outside a
  ``[run:]``/``[claim:]`` marker, so free text (a profile field, a study label) cannot launder a number.
* **Markers only from verified rows.** Free-text fields (profile, study label, site name/type/id, project
  title) are passed through ``neutralise`` before anything else: ``[run:``/``[claim:``/``[lit:`` syntax is
  defused, so text an agent can write (``update_researcher_profile``, ``set_site_name``, a title) can never
  supply the marker that licenses a number. Only the lines built here from run-log rows and ledger claims
  carry markers.
* **Profile <= 1 KB.** The stored profile fields (the file does not record who wrote a field: a person or
  the agent via ``update_researcher_profile``, so treat them as unverified text; they are neutralised and
  gated). Agent observations are consent-gated (PSMH T3) and not injected here.

``RESEARCH_MD_STUB`` is the one-release replacement (M8) for ``.aihydrorules/research.md``.
"""
from __future__ import annotations

import json
import logging
import math
import re
from decimal import Decimal
from typing import Any

log = logging.getLogger("ai_hydro.session.study_context")

PROFILE_MAX_BYTES = 1024
MAX_RUNS = 8
MAX_VALUES_PER_RUN = 6
MAX_CLAIMS = 12

_BARE_CATEGORIES = frozenset({"quantity", "sample_size", "method_param"})
WITHHELD = "[line withheld: it carried a number with no [run:]/[claim:] marker]"

CITATION_GRAMMAR = (
    "## Citation grammar\n"
    "Every quantity you write needs a marker in the same sentence: `[run:<run_id>#key_outputs.<field>]` "
    "for a value from a tool run, `[claim:<claim_id>]` for a ledger claim, `[lit:<tag>]` for a literature "
    "value. Take run ids and fields from the Results above or from `get_session_summary`. "
    "`write_research_interpretation` refuses prose with an uncited quantity."
)

STUB_MARKER = "<!-- aihydro:research-md-stub -->"
RESEARCH_MD_STUB = (
    f"{STUB_MARKER}\n"
    "# AI-Hydro research context\n\n"
    "AI-Hydro now injects project and study context directly (the `aihydro://project/{project_id}/context` "
    "resource). This file is no longer updated and can be deleted. It is kept for one release so older "
    "hosts do not break.\n"
)


# ---------------------------------------------------------------------------
# research.md stub (M8)
# ---------------------------------------------------------------------------

_DIGEST_HEADS = ("# Research Session", "# Research Project:")
_DIGEST_FOOTS = ("Skeleton auto-generated by HydroSession", "Auto-generated by ProjectSession")


def _is_generated_digest(text: str) -> bool:
    """True for a file AI-Hydro itself generated (the retired session or project digest)."""
    t = text.strip()
    return t.startswith(_DIGEST_HEADS) and any(f in t for f in _DIGEST_FOOTS)


def write_research_md_stub(workspace_dir: str | None = None) -> bool:
    """Make ``.aihydrorules/research.md`` the stub. Returns True when the file was (re)written.

    Idempotent: a file that already is the stub is not touched (its mtime stays), so nothing rewrites
    ``research.md`` after the stub. A file that is neither the stub nor a digest AI-Hydro generated (a
    person edited or replaced it) is copied once to ``research.md.bak-<UTC timestamp>`` before the stub
    replaces it. Failures are logged and swallowed; the digest is not on this path.
    """
    from datetime import datetime, timezone

    from ai_hydro.registry.paths import rules_dir

    path = rules_dir(workspace_dir) / "research.md"
    try:
        if path.is_file():
            old = path.read_text(encoding="utf-8", errors="replace")
            if STUB_MARKER in old:
                return False
            if not _is_generated_digest(old):
                stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
                bak = path.with_name(f"research.md.bak-{stamp}")
                n = 0
                while bak.exists():
                    n += 1
                    bak = path.with_name(f"research.md.bak-{stamp}-{n}")
                bak.write_text(old, encoding="utf-8")
                log.warning("research.md was not an AI-Hydro digest; kept a copy at %s", bak)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(RESEARCH_MD_STUB, encoding="utf-8")
        return True
    except OSError as exc:
        log.warning("research.md stub not written (%s): %s", path, exc)
        return False


# ---------------------------------------------------------------------------
# The numeric gate
# ---------------------------------------------------------------------------

_MARKER_OPEN = re.compile(r"\[\s*(run|claim|lit)\s*:", re.IGNORECASE)
# Exempt classifications that name no fixed kind of token: any plain integer, any digit string beside
# "USGS", any "17 things". Only a known id may use them here.
_LOOSE_EXEMPT = frozenset({"bare_integer", "identifier", "meta_count"})


def neutralise(text: Any) -> str:
    """Free text with marker syntax defused (``[run:`` becomes ``(run :``) and whitespace collapsed.

    Applied to every field an agent or person can write, so such text can never supply the marker that
    licenses a number in the gate below.
    """
    return _MARKER_OPEN.sub(lambda m: f"({m.group(1).lower()} :", " ".join(str(text or "").split()))


def bare_numbers(text: str, known_ids: tuple[str, ...] = ()) -> list[str]:
    """Numeric literals in ``text`` that are neither exempt (year, date, Figure N, ...) nor cited.

    A number is cited when a ``[run:]`` marker follows it in the same sentence/bullet/cell, or a
    ``[claim:]`` marker sits in that segment (a claim marker binds its sentence). ``[lit:]`` does not
    count: this context carries stored results, not literature constants. The grammar's loose
    exemptions (a plain integer, a long digit string, a "17 things" count) hold only for ``known_ids``
    (the study's site id): "population 12345678" is flagged.
    """
    from ai_hydro.audit.grammar import MarkerKind, classify_numerics, extract_markers, segment_of, segments

    allowed = {str(i).strip() for i in known_ids if str(i).strip()}
    markers = [m for m in extract_markers(text) if m.kind in (MarkerKind.RUN, MarkerKind.CLAIM)]
    segs = segments(text)
    out: list[str] = []
    for c in classify_numerics(text, known_ids):
        raw = c.span.raw.strip()
        if c.category == "exempt":
            if c.reason not in _LOOSE_EXEMPT or raw in allowed:
                continue
        elif c.category not in _BARE_CATEGORIES:
            continue
        lo, hi = segment_of(segs, c.span.start)
        cited = any(
            (m.kind == MarkerKind.RUN and c.span.end <= m.start < hi)
            or (m.kind == MarkerKind.CLAIM and lo <= m.start < hi)
            for m in markers
        )
        if not cited:
            out.append(c.span.raw)
    return out


def _gate_lines(lines: list[str], known_ids: tuple[str, ...]) -> list[str]:
    out = []
    for line in lines:
        out.append(line if not line.strip() or not bare_numbers(line, known_ids) else WITHHELD)
    return out


