# Study digest
# ---------------------------------------------------------------------------

def _scalar(v: Any) -> str | None:
    """A readable plain-decimal rendering (six significant digits); exponent form only for extreme values."""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return None
    if isinstance(v, float) and not math.isfinite(v):
        return None
    if v == 0:
        return "0"
    if abs(v) >= 1e15 or abs(v) < 1e-9:
        return format(v, ".6e")
    text = format(v, ".6g")
    if "e" in text:                               # 1e+06 -> 1000000, 1e-07 -> 0.0000001
        text = format(Decimal(text), "f")
    return text


def _marker_safe(s: str) -> bool:
    import re

    return bool(re.fullmatch(r"[A-Za-z0-9._\-]+", s or ""))


def _key_results(session_id: str, healthy_slots: list[str]) -> list[str]:
    """``name = value [run:id#key_outputs.name]`` lines, read from the run log now (never remembered)."""
    from ai_hydro.session import store as _store
    from ai_hydro.session.run_records import verify_run_log_entry

    try:
        log_rows = _store._run_log_read_all(session_id)
    except Exception:
        return []
    latest: dict[str, tuple[str, dict]] = {}
    for run_id, entry in log_rows.items():                   # ordered by timestamp: the last row wins
        if isinstance(entry, dict) and entry.get("slot") in healthy_slots:
            latest[entry["slot"]] = (run_id, entry)
    lines: list[str] = []
    for slot in healthy_slots[:MAX_RUNS]:
        if slot not in latest:
            continue
        run_id, entry = latest[slot]
        if not _marker_safe(run_id):
            continue
        check = verify_run_log_entry(entry)
        if check["has_record"] and (check["record_ok"] is False or check["entry_ok"] is False):
            lines.append(f"- {slot}: stale pointer [run:{run_id}] (the record no longer verifies; re-run)")
            continue
        n = 0
        for key, val in (entry.get("key_outputs") or {}).items():
            text = _scalar(val)
            if text is None or not _marker_safe(str(key)):
                continue
            lines.append(f"- {key} = {text} [run:{run_id}#key_outputs.{key}]")
            n += 1
            if n >= MAX_VALUES_PER_RUN:
                break
    return lines


def _study_lines(study_id: str, label: str) -> list[str]:
    from ai_hydro.session import HydroSession
    from ai_hydro.session.store import _SESSIONS_DIR

    lines = ["## Active study", f"**Study**: {neutralise(label)}", f"**Study id**: `{study_id}`"]
    if not (_SESSIONS_DIR / f"{study_id}.json").is_file():
        lines.append("_The study file is missing; nothing to show._")
        return lines
    s = HydroSession.load(study_id)
    if s.site_id:
        lines.append(f"**Site**: {neutralise(s.site_id)}" + (f" ({neutralise(s.site_type)})" if s.site_type else ""))
    if s.archived:
        lines.append("> This study is ARCHIVED.")
    computed = s.computed_healthy()
    stale = [c for c in computed if s.is_stale(c)]
    active = [c for c in computed if c not in stale]
    if active:
        lines.append("**Computed**: " + ", ".join(active))
    if stale:
        lines.append("**Computed (stale)**: " + ", ".join(stale))
    degraded = s.degraded()
    if degraded:
        lines.append("**Degraded (do not cite; re-run)**: " + "; ".join(f"{d['slot']} ({d['health']})" for d in degraded))
    pending = s.pending()
    if pending:
        lines.append("**Pending**: " + ", ".join(pending))
    for w in s.validate_identity():
        if w.get("severity") in ("warn", "error"):
            lines.append(f"> Identity warning `{w.get('code')}`: investigate before exporting.")
    results = _key_results(study_id, active)
    if results:
        lines += ["", "**Results** (read from the run log just now; cite them with their marker):", *results]
    claims = [(cid, c) for cid, c in (s.claims or {}).items() if isinstance(c, dict) and _marker_safe(str(cid))]
    if claims:
        lines += ["", "**Claims**:"]
        for cid, c in claims[:MAX_CLAIMS]:
            status = str(c.get("status") or "").strip()
            lines.append(f"- [claim:{cid}]" + (f" ({status})" if status.isidentifier() else ""))
    if s.interpretation:
        when = (s.interpretation_at or "")[:10]
        lines.append("")
        lines.append("**Interpretation**: written" + (f" {when}" if when else "")
                     + (" (stale)" if s.is_stale("interpretation") else "")
                     + "; read it with `get_session_summary`.")
    return lines


def build_context(project_id: str, chat_id: str | None) -> dict[str, Any]:
    """The context resource body: ``{found, project_id, chat_id, active_study_id, text}``. No side effects."""
    from ai_hydro.session.chat_binding import get_binding_store, is_valid_chat_id
    from ai_hydro.session.project_registry import get_project_registry

    reg = get_project_registry()
    rec = reg.get(project_id)
    if rec is None:
        return {"found": False, "project_id": project_id}

    chat = (chat_id or "").strip()
    note = ""
    study_id: str | None = None
    if not chat:
        note = "No chat was given, so no study is active."
    elif not is_valid_chat_id(chat):
        note = "The chat id is not valid, so no study is active."
    else:
        bound = get_binding_store().lookup_study(chat)
        members = {s.get("study_id") for s in rec.get("studies", [])}
        if not bound:
            note = "This chat is not bound to a study. Start or resume one with `start_session`."
        elif bound not in members:
            note = "This chat's study belongs to another project, so it is not shown here."
        else:
            study_id = bound

    parts: list[str] = [f"# Project: {_project_title(rec)}"]
    known: tuple[str, ...] = ()
    if study_id:
        view = reg.view(rec)
        row = next((r for r in view["studies"] if r["study_id"] == study_id), None)
        sid_site = neutralise((row or {}).get("site_id"))
        known = (sid_site,) if sid_site else ()
        label = neutralise(row["label"] if row else f"{study_id} (unnamed study)")
        if bare_numbers(label, known):                  # a coordinate label is a measured value: use the id
            label = f"{study_id} (unnamed study)"
        parts += ["", *_gate_lines(_study_lines(study_id, label), known)]
    else:
        parts += ["", "## Active study", f"_{note}_"]
    parts += ["", CITATION_GRAMMAR]
    prof = profile_block()
    if prof:
        parts += ["", prof]
    text = "\n".join(_gate_lines("\n".join(parts).split("\n"), known))
    return {
        "found": True, "project_id": project_id, "chat_id": chat or None,
        "active_study_id": study_id, "text": text,
    }


def _project_title(rec: dict[str, Any]) -> str:
    title = neutralise(rec.get("title")) or "Untitled project"
    return title if not bare_numbers(title) else "Untitled project"
