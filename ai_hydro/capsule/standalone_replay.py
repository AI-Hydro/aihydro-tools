#!/usr/bin/env python3
"""
AI-Hydro capsule verifier — replay.py

Generated by ai_hydro.mcp.tools_session.export_session. Standard library only;
it does not import ai_hydro.

This script checks the archive. It does NOT re-run any computation, and it
prints exactly which level it reached:

    archive_integrity  every file matches its recorded SHA-256 and every v2
                       run record verifies (record seal and the binding to its
                       run-log row). Says nothing about whether the numbers
                       would be produced again.
    cross_check        (--live, at least one comparison, all passed) numeric
                       outputs in run_log.json agree with the values retained
                       in session.json. Still no recomputation.
    not_performed      an integrity check failed; no level is established.

Usage:
    python replay.py                     # archive integrity
    python replay.py --live              # also cross-check run log vs session
    python replay.py --tolerance=0.02    # allow 2% deviation (default 1%)

Exit code: 0 = all checks passed, 1 = a check failed,
           2 = --live found no comparable values (nothing was cross-checked).
"""
from __future__ import annotations

import decimal
import hashlib
import json
import math
import sys
from pathlib import Path

MANIFEST_FILE = "capsule_manifest.json"
DEFAULT_TOLERANCE = 0.01

# Legacy exports (and hand-built fixtures) keep slots under session["slots"].
_LEGACY_TOOL_TO_SLOT = {
    "extract_hydrological_signatures": "signatures",
    "extract_geomorphic_parameters": "geomorphic",
    "compute_twi": "twi",
    "separate_baseflow": "baseflow",
    "train_hydro_model": "model",
    "get_model_results": "model",
    "delineate_watershed": "watershed",
    "delineate_watershed_from_point": "watershed",
    "fetch_streamflow_data": "streamflow",
}


# --------------------------------------------------------------------------- #
# aihydro.c14n/1 for JSON-native values (record dicts read back from JSON):
# tagging (non-finite floats, ints beyond 2**53, "$"-keyed dicts) followed by
# RFC 8785 (JCS) serialisation. Copied from aihydro_core.records.canonical;
# tests assert it reproduces core's golden vectors and digests.
# --------------------------------------------------------------------------- #

_MAX_SAFE_INT = 2 ** 53


def _encode(value):
    if value is None or isinstance(value, (bool, str)):
        return value
    if isinstance(value, int):
        if -_MAX_SAFE_INT <= value <= _MAX_SAFE_INT:
            return value
        return {"$int": str(int(value))}
    if isinstance(value, float):
        if math.isnan(value):
            return {"$float": "nan"}
        if math.isinf(value):
            return {"$float": "inf" if value > 0 else "-inf"}
        return float(value)
    if isinstance(value, dict):
        out = {}
        for key, item in value.items():
            skey = key if isinstance(key, str) else str(key)
            out[skey] = _encode(item)
        if any(k.startswith("$") for k in out):
            return {"$map": out}
        return out
    if isinstance(value, (list, tuple)):
        return [_encode(v) for v in value]
    raise TypeError(f"cannot encode {type(value).__name__}")


def _es_number(x):
    """ECMAScript Number::toString for a finite double (RFC 8785 3.2.2.3)."""
    if x == 0:
        return "0"
    if x < 0:
        return "-" + _es_number(-x)
    sign, digit_tuple, exp = decimal.Decimal(repr(x)).as_tuple()
    digits = "".join(map(str, digit_tuple)).rstrip("0") or "0"
    k = len(digits)
    n = len(digit_tuple) + exp
    if k <= n <= 21:
        return digits + "0" * (n - k)
    if 0 < n <= 21:
        return digits[:n] + "." + digits[n:]
    if -6 < n <= 0:
        return "0." + "0" * (-n) + digits
    e = n - 1
    exp_str = ("+" if e >= 0 else "-") + str(abs(e))
    if k == 1:
        return digits + "e" + exp_str
    return digits[0] + "." + digits[1:] + "e" + exp_str


_ESCAPES = {'"': '\\"', "\\": "\\\\", "\b": "\\b", "\f": "\\f", "\n": "\\n", "\r": "\\r", "\t": "\\t"}


def _es_string(s):
    out = ['"']
    for ch in s:
        if ch in _ESCAPES:
            out.append(_ESCAPES[ch])
        elif ord(ch) < 0x20:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def _serialize(v):
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return _es_number(v)
    if isinstance(v, str):
        return _es_string(v)
    if isinstance(v, list):
        return "[" + ",".join(_serialize(i) for i in v) + "]"
    items = sorted(v.items(), key=lambda kv: kv[0].encode("utf-16-be", "surrogatepass"))
    return "{" + ",".join(_es_string(k) + ":" + _serialize(val) for k, val in items) + "}"


def canonical_bytes(value) -> bytes:
    return _serialize(_encode(value)).encode("utf-8")


def c14n_digest(value) -> str:
    return "sha256:" + hashlib.sha256(canonical_bytes(value)).hexdigest()


_RECORD_DEFAULTS = (
    ("schema", "aihydro.run/2"), ("canonicalization", "aihydro.c14n/1"),
    ("status", "ok"), ("input_refs", []), ("parents", []), ("extra", {}),
)


def record_seal_ok(record: dict) -> bool:
    """True iff ``record`` is sealed and unchanged (mirrors RunRecord.verify)."""
    declared = record.get("record_digest")
    if not declared:
        return False
    payload = {k: v for k, v in record.items() if k != "record_digest" and v is not None}
    for name, default in _RECORD_DEFAULTS:
        payload.setdefault(name, default)
    try:
        return c14n_digest(payload) == declared
    except Exception:
        return False


def verify_run_log(run_log: dict) -> dict:
    """Verify every v2 record in a run log. Rows without a record are legacy."""
    summary = {"rows": 0, "v2_records": 0, "verified": 0, "unbound": 0, "legacy": 0,
               "record_errors": 0, "failures": []}
    for run_id, entry in sorted(run_log.items()):
        summary["rows"] += 1
        record = entry.get("record") if isinstance(entry, dict) else None
        if not isinstance(record, dict):
            summary["legacy"] += 1
            continue
        summary["v2_records"] += 1
        if record.get("record_error"):
            summary["record_errors"] += 1
        if record.get("run_id") != run_id:
            summary["failures"].append((run_id, "record.run_id does not match its row"))
            continue
        if not record_seal_ok(record):
            summary["failures"].append((run_id, "record_digest mismatch"))
            continue
        expected = (record.get("extra") or {}).get("entry_digest")
        if expected is None:
            summary["unbound"] += 1     # sealed but not bound to its row: not "verified"
            continue
        if expected is not None:
            body = {k: v for k, v in entry.items() if k != "record"}
            try:
                actual = c14n_digest(body)
            except Exception:
                actual = None
            if actual != expected:
                summary["failures"].append((run_id, "run-log row changed after its record was sealed"))
                continue
        summary["verified"] += 1
    return summary


