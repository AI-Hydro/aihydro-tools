# Live cross-check: run log vs the values retained in session.json
# --------------------------------------------------------------------------- #

def _slot_results(raw: dict) -> list:
    """Every retained slot result as ``(slot, result_dict)``.

    Real exports store slots as top-level keys shaped
    ``{feature_id: {params_key: {"data":..., "meta":...}}}`` (flag
    ``_hydro_slots_v2``). Older fixtures put ``{"data":...}`` under
    ``session["slots"][slot]``; both are read.
    """
    found = []
    legacy = raw.get("slots")
    if isinstance(legacy, dict):
        for slot, result in legacy.items():
            if isinstance(result, dict):
                found.append((slot, result))
    for slot, value in raw.items():
        if slot == "slots" or not isinstance(value, dict):
            continue
        if not (raw.get("_hydro_slots_v2") or "__legacy__" in value):
            continue
        for by_key in value.values():
            if not isinstance(by_key, dict):
                continue
            for result in by_key.values():
                if isinstance(result, dict) and isinstance(result.get("data"), dict):
                    found.append((slot, result))
    return found


def _computed_at(result: dict) -> str:
    meta = result.get("meta")
    return str(meta.get("computed_at", "")) if isinstance(meta, dict) else ""


def _candidate(entry: dict, run_id: str, results: list, is_latest_for_tool: bool):
    """The retained result a run-log row can honestly be compared with."""
    exact = [r for _, r in results
             if isinstance(r.get("meta"), dict) and r["meta"].get("run_id") == run_id]
    if exact:
        return exact[0], "run_id"
    if not is_latest_for_tool:
        return None, "superseded by a later run of the same tool"
    tool = entry.get("tool_name", "")
    same_tool = [r for _, r in results
                 if isinstance(r.get("meta"), dict) and r["meta"].get("tool") == tool]
    if not same_tool and tool in _LEGACY_TOOL_TO_SLOT:
        same_tool = [r for slot, r in results if slot == _LEGACY_TOOL_TO_SLOT[tool]]
    if not same_tool:
        return None, "no retained result for this tool"
    return max(same_tool, key=_computed_at), "latest result of the same tool"


def live_cross_check(capsule_dir: Path, tolerance: float = DEFAULT_TOLERANCE):
    """Compare numeric ``key_outputs`` with retained slot values.

    Returns ``(comparisons, skipped)``. Each comparison has run_id, key,
    expected, actual, deviation_pct, status. Nothing is recomputed.
    """
    rl_path = capsule_dir / "run_log.json"
    sj_path = capsule_dir / "session.json"
    if not rl_path.exists() or not sj_path.exists():
        return [], [("-", "run_log.json or session.json not found")]
    run_log = json.loads(rl_path.read_text(encoding="utf-8"))
    raw = json.loads(sj_path.read_text(encoding="utf-8"))
    results = _slot_results(raw)

    latest = {}
    for run_id, entry in run_log.items():
        if not isinstance(entry, dict):
            continue
        tool = entry.get("tool_name", "")
        stamp = str(entry.get("timestamp", ""))
        if tool not in latest or (stamp, run_id) > latest[tool]:
            latest[tool] = (stamp, run_id)

    comparisons, skipped = [], []
    for run_id, entry in sorted(run_log.items()):
        if not isinstance(entry, dict):
            continue
        key_outputs = entry.get("key_outputs")
        if not isinstance(key_outputs, dict) or not key_outputs:
            continue
        is_latest = latest.get(entry.get("tool_name", ""), (None, None))[1] == run_id
        result, how = _candidate(entry, run_id, results, is_latest)
        if result is None:
            skipped.append((run_id, how))
            continue
        data = result.get("data") if isinstance(result.get("data"), dict) else {}
        for key, expected in key_outputs.items():
            if key.startswith("_") or isinstance(expected, bool) or not isinstance(expected, (int, float)):
                continue
            actual = data.get(key)
            if isinstance(actual, bool) or not isinstance(actual, (int, float)):
                continue
            if not (math.isfinite(expected) and math.isfinite(actual)):
                continue
            if expected == 0:
                deviation = 0.0 if abs(actual) < 1e-9 else float("inf")
            else:
                deviation = abs(actual - expected) / abs(expected)
            comparisons.append({
                "run_id": run_id, "key": key, "expected": expected, "actual": actual,
                "deviation_pct": round(deviation * 100, 3), "matched_by": how,
                "status": "pass" if deviation <= tolerance else "fail",
            })
    return comparisons, skipped


# --------------------------------------------------------------------------- #
# Reporting
# --------------------------------------------------------------------------- #

def replay_status(integrity_ok: bool, live: bool, n_comparisons: int, comparisons_ok: bool) -> str:
    """The strongest level actually reached. Never ``recomputed``."""
    if not integrity_ok:
        return "not_performed"
    if live and n_comparisons > 0 and comparisons_ok:
        return "cross_check"
    return "archive_integrity"


def run(capsule_dir: Path, live: bool = False, tolerance: float = DEFAULT_TOLERANCE, out=print) -> int:
    hashes_ok, hash_results = verify_hashes(capsule_dir, out=out)
    n_pass = sum(1 for r in hash_results if r["status"] == "pass")
    n_bad = sum(1 for r in hash_results if r["status"] != "pass")
    out(f"\nHash check: {n_pass} pass, {n_bad} fail")

    records_ok = True
    rl_path = capsule_dir / "run_log.json"
    if rl_path.exists():
        summary = verify_run_log(json.loads(rl_path.read_text(encoding="utf-8")))
        for run_id, why in summary["failures"]:
            out(f"FAIL  record {run_id}: {why}")
        records_ok = not summary["failures"]
        out(f"Run records: {summary['verified']} of {summary['v2_records']} v2 records verify; "
            f"{summary['unbound']} sealed but unbound to their row; "
            f"{summary['legacy']} legacy rows have no record; {summary['record_errors']} carry a record_error")
    else:
        out("Run records: run_log.json not found")

    bindings_ok = verify_data_bindings(capsule_dir, out=out)

    comparisons, comparisons_ok = [], True
    if live:
        comparisons, skipped = live_cross_check(capsule_dir, tolerance)
        for c in comparisons:
            if c["status"] == "pass":
                out(f"PASS  {c['run_id']}:{c['key']}  {c['expected']:.4g} ~ {c['actual']:.4g}")
            else:
                out(f"FAIL  {c['run_id']}:{c['key']}  expected={c['expected']:.4g}  "
                    f"got={c['actual']:.4g}  ({c['deviation_pct']:.1f}%)")
        comparisons_ok = all(c["status"] == "pass" for c in comparisons)
        for run_id, why in skipped:
            out(f"SKIP  {run_id}: {why}")

    integrity_ok = hashes_ok and records_ok and bindings_ok
    if not hash_results and not (rl_path.exists() and summary["v2_records"]):
        integrity_ok = False        # nothing was actually checked
        out("FAIL  archive has no files and no records; nothing was verified.")
    status = replay_status(integrity_ok, live, len(comparisons), comparisons_ok)
    out(f"\nreplay_status: {status}")
    out("recomputation: not_performed")
    if live:
        out(f"comparisons: {len(comparisons)}")

    if not (integrity_ok and comparisons_ok):
        return 1
    if live and not comparisons:
        out("FAIL  --live found no comparable values; nothing was cross-checked.")
        return 2
    return 0


def main(argv=None, capsule_dir: Path | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    tolerance = DEFAULT_TOLERANCE
    for arg in argv:
        if arg.startswith("--tolerance="):
            try:
                tolerance = float(arg.split("=", 1)[1])
            except ValueError:
                pass
    return run(capsule_dir or Path(__file__).parent, live="--live" in argv, tolerance=tolerance)


def source_text() -> str:
    """The text written to a capsule as ``replay.py`` (this file, verbatim)."""
    return Path(__file__).read_text(encoding="utf-8")



def _listed_data_paths(capsule_dir: Path) -> set:
    """data/ paths the manifest claims the capsule carries (files + data_artifacts)."""
    try:
        m = json.loads((capsule_dir / MANIFEST_FILE).read_text(encoding="utf-8"))
    except Exception:
        return set()
    listed = {e.get("path") for e in m.get("files") or [] if isinstance(e, dict)}
    for art in m.get("data_artifacts") or []:
        if isinstance(art, dict):
            listed.add(art.get("path"))
            listed.add(art.get("retained_artifact", {}).get("path") if isinstance(art.get("retained_artifact"), dict) else None)
    return {x for x in listed if isinstance(x, str) and x.startswith("data/")}

if __name__ == "__main__":
    sys.exit(main())
