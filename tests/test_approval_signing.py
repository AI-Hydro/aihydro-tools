def _fake_sshsig(key_type: str) -> tuple:
    blob = struct.pack(">I", len(key_type)) + key_type.encode() + struct.pack(">I", 32) + b"\x07" * 32
    ns = trust.NAMESPACE.encode()
    raw = (b"SSHSIG" + struct.pack(">I", 1) + struct.pack(">I", len(blob)) + blob
           + struct.pack(">I", len(ns)) + ns + struct.pack(">I", 0) + struct.pack(">I", 6) + b"sha512"
           + struct.pack(">I", 0))
    b64 = base64.b64encode(raw).decode()
    armored = "-----BEGIN SSH SIGNATURE-----\n" + b64 + "\n-----END SSH SIGNATURE-----\n"
    return armored, blob


@pytest.mark.parametrize("key_type,options,expect", [
    ("sk-ssh-ed25519@openssh.com", 'namespaces="aihydro-approval@v1"', "ssh_sig_sk_user_trust"),
    ("sk-ecdsa-sha2-nistp256@openssh.com", "", "ssh_sig_sk_user_trust"),
    ("sk-ssh-ed25519@openssh.com", "no-touch-required", "ssh_sig_user_trust"),   # touch not enforced: not claimed
    ("ssh-ed25519", "", "ssh_sig_user_trust"),
])
def test_channel_is_derived_from_key_type_and_touch_policy(scratch_home, monkeypatch, key_type, options, expect):
    armored, blob = _fake_sshsig(key_type)
    fp = trust.key_fingerprint(blob)
    trust.user_trust_file().parent.mkdir(parents=True)
    trust.user_trust_file().write_text(
        f"alice {options + ' ' if options else ''}{key_type} {base64.b64encode(blob).decode()}\n")

    class R:
        def __init__(self, out): self.returncode, self.stdout, self.stderr = 0, out, b""

    def fake_run(args, data=b""):
        return R(b"alice\n" if "find-principals" in args else b"Good signature\n")

    monkeypatch.setattr(trust, "_run", fake_run)
    rec = records.seal_record({**BODY, "schema": records.APPROVAL_SCHEMA_V2,
                               "signer": {"fingerprint": fp, "key_type": key_type}})
    rec["signature"] = {"format": "sshsig", "namespace": trust.NAMESPACE, "armored": armored}
    verdict = trust.check_approval(rec)
    assert verdict.ok and verdict.channel == expect
    # a record that merely *says* it is sk-signed gets no such label
    rec2 = {**rec, "channel": "ssh_sig_sk_system_trust"}
    assert trust.check_approval(rec2).channel == expect


