def _drive_cli(args: list, tmp_path: Path, rev: str, env_extra: dict) -> tuple:
    import pty

    env = {**os.environ, "HOME": str(tmp_path), "AIHYDRO_HOME": str(tmp_path / "state"),
           "AIHYDRO_SYSTEM_TRUST_FILE": str(tmp_path / "etc" / "allowed_signers"),
           "PYTHONPATH": os.pathsep.join(filter(None, [str(REPO), os.environ.get("PYTHONPATH", "")])),
           **env_extra}
    env.pop("SSH_AUTH_SOCK", None)
    if "AIHYDRO_REQUIRE_SIGNED" not in env_extra:
        env.pop("AIHYDRO_REQUIRE_SIGNED", None)       # approval_helpers sets the dev opt-out at import
    master, slave = pty.openpty()
    proc = subprocess.Popen([sys.executable, "-m", "ai_hydro.approval.cli", *args],
                            stdin=slave, stdout=slave, stderr=slave, env=env, cwd=str(REPO), close_fds=True)
    os.close(slave)
    seen, typed, deadline = b"", False, time.time() + 120
    while time.time() < deadline:
        ready, _, _ = select.select([master], [], [], 0.5)
        if ready:
            try:
                chunk = os.read(master, 4096)
            except OSError:
                break
            if not chunk:
                break
            seen += chunk
        if not typed and b"hex characters" in seen:
            os.write(master, (rev.split(":")[1][:12] + "\n").encode())
            typed = True
        if proc.poll() is not None and not ready:
            break
    code = proc.wait(timeout=30)
    os.close(master)
    return code, seen.decode(errors="replace")


