def _insert_path_row(path_text):
    rows = cr.history("rev")["c1"]["rows"]
    prev = ClaimRevision.from_dict(rows[-1])
    content = {**prev.content, "note": f"data read from {path_text}"}
    new = ClaimRevision(session_id="rev", claim_id="c1", revision=prev.revision + 1,
                        supersedes=prev.revision_digest, revision_digest=digest(content),
                        content=content, cause={"tool": "update_claim_status", "reason": "redefined"},
                        actor=prev.actor).seal()
    conn = cr._connect("rev", create=False)
    cr._insert_sealed(conn, new)
    conn.close()
    return new


