def _doc(cap: Path) -> dict:
    return json.loads((cap / "records" / "claim_revisions.json").read_text(encoding="utf-8"))


# ---------------------------------------------------------------- round trip
def test_real_store_round_trip_verifies_in_stdlib(session, tmp_path):
    _add(); _supported(); _add("c2")
    cap = tmp_path / "cap"
    entries, counts = collect_claim_revisions("rev", cap, tmp_path)
    assert [e["claim_id"] for e in entries] == ["c1", "c2"]
    assert counts == {"claims": 2, "ok": 2, "corrupt": 0, "revisions": counts["revisions"],
                      "redacted": 0, "source": counts["source"]}
    assert counts["revisions"] >= 3
    doc = _doc(cap)
    store_rows = cr.history("rev")
    for cid in ("c1", "c2"):                        # verbatim: sealed rows unchanged
        assert doc["claims"][cid]["rows"] == store_rows[cid]["rows"]
        assert verify_chain([ClaimRevision.from_dict(r) for r in doc["claims"][cid]["rows"]])
    heads = {e["claim_id"]: e["head_revision_digest"] for e in entries}
    verdicts = ccv.verify_exported(doc, heads)
    assert {c: v["status"] for c, v in verdicts.items()} == {"c1": "verified", "c2": "verified"}


