def test_truncated_chain_needs_an_anchor(session, tmp_path):
    """A cut tail still chains; only an external head anchor exposes it (documented limit)."""
    _add(); _supported()
    cap = tmp_path / "cap"
    entries, _ = collect_claim_revisions("rev", cap, tmp_path)
    head = entries[0]["head_revision_digest"]
    doc = _doc(cap)
    doc["claims"]["c1"]["rows"] = doc["claims"]["c1"]["rows"][:-1]
    assert ccv.verify_exported(doc)["c1"]["status"] == "verified"          # chain alone cannot tell
    assert ccv.verify_exported(doc, {"c1": head})["c1"]["status"] == "failed"
    # the same truncation made in the store itself is likewise invisible to the chain
    conn = _raw()
    conn.execute("DELETE FROM claim_revisions WHERE claim_id='c1' AND revision >= 1")
    conn.close()
    entries2, _ = collect_claim_revisions("rev", tmp_path / "cap2", tmp_path)
    assert entries2[0]["status"] == "ok" and entries2[0]["head_revision_digest"] != head


